#!/usr/bin/env python3
"""Generate the embedded boot-secrets header.

Reads an untracked local file of `name = value` lines and emits a C header the
kernel compiles in. When the file is absent -- which is the normal case, and
the case for every build anyone else makes -- the header declares an empty
table and the kernel embeds nothing.

The input file is gitignored. The output lands under build/, which is also
gitignored. Neither can reach the repository through an ordinary commit.

This exists for bringing a machine onto a network and seeding named provider
credentials before it has any other way to be configured. A kernel built this
way carries the values in plaintext in the image; see the warning the kernel
prints at boot.
"""

import argparse
import os
import stat
import sys

ALLOWED = {
    "wifi-ssid": "ANX_CRED_OPAQUE",
    "wifi-pass": "ANX_CRED_OPAQUE",
    "jev-api-key": "ANX_CRED_API_KEY",
    "openai-api-key": "ANX_CRED_API_KEY",
    "anthropic-api-key": "ANX_CRED_API_KEY",
}
MAX_VALUE_BYTES = 255


def c_escape(s: str) -> str:
    out = []
    for ch in s:
        if ch in ('"', "\\"):
            out.append("\\" + ch)
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            out.append("\\x%02x" % ord(ch))
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True)
    ap.add_argument("--header", required=True)
    args = ap.parse_args()

    entries = []
    if os.path.exists(args.input):
        if os.path.islink(args.input):
            sys.stderr.write("%s: refusing a symlinked secrets file\n" % args.input)
            return 1
        input_stat = os.stat(args.input)
        if not stat.S_ISREG(input_stat.st_mode):
            sys.stderr.write("%s: secrets input is not a regular file\n" % args.input)
            return 1
        if stat.S_IMODE(input_stat.st_mode) != 0o600:
            sys.stderr.write("%s: secrets file mode must be 0600\n" % args.input)
            return 1
        seen = set()
        with open(args.input, "r", encoding="utf-8") as fh:
            for lineno, raw in enumerate(fh, 1):
                line = raw.strip()
                if not line or line.startswith("#"):
                    continue
                if "=" not in line:
                    sys.stderr.write(
                        "%s:%d: expected name = value\n" % (args.input, lineno))
                    return 1
                name, value = line.split("=", 1)
                name = name.strip()
                value = value.strip()
                if name not in ALLOWED:
                    sys.stderr.write(
                        "%s:%d: '%s' is not an injectable name (allowed: %s)\n"
                        % (args.input, lineno, name, ", ".join(sorted(ALLOWED))))
                    return 1
                if name in seen:
                    sys.stderr.write(
                        "%s:%d: duplicate injectable name '%s'\n"
                        % (args.input, lineno, name))
                    return 1
                try:
                    encoded = value.encode("ascii")
                except UnicodeEncodeError:
                    sys.stderr.write(
                        "%s:%d: value for '%s' must be ASCII\n"
                        % (args.input, lineno, name))
                    return 1
                if not encoded:
                    sys.stderr.write(
                        "%s:%d: value for '%s' must not be empty\n"
                        % (args.input, lineno, name))
                    return 1
                if len(encoded) > MAX_VALUE_BYTES:
                    sys.stderr.write(
                        "%s:%d: value for '%s' exceeds %d bytes\n"
                        % (args.input, lineno, name, MAX_VALUE_BYTES))
                    return 1
                if any(byte < 0x20 or byte > 0x7e for byte in encoded):
                    sys.stderr.write(
                        "%s:%d: value for '%s' must be printable ASCII\n"
                        % (args.input, lineno, name))
                    return 1
                seen.add(name)
                entries.append((name, value, ALLOWED[name]))

    os.makedirs(os.path.dirname(args.header), exist_ok=True)
    with open(args.header, "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/gen_boot_secrets.py. Do not edit. */\n")
        out.write("#ifndef ANX_BOOT_SECRETS_H\n#define ANX_BOOT_SECRETS_H\n\n")
        out.write("struct anx_boot_secret {\n\tconst char *name;\n"
                  "\tconst char *value;\n"
                  "\tenum anx_credential_type type;\n};\n\n")
        out.write("static const struct anx_boot_secret anx_boot_secrets[] = {\n")
        for name, value, cred_type in entries:
            out.write('\t{ "%s", "%s", %s },\n'
                      % (c_escape(name), c_escape(value), cred_type))
        out.write("\t{ 0, 0, ANX_CRED_OPAQUE }\n};\n\n")
        out.write("#define ANX_BOOT_SECRET_COUNT %d\n\n" % len(entries))
        out.write("#endif /* ANX_BOOT_SECRETS_H */\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
