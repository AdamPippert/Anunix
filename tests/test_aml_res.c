static uint8_t blob[sizeof(aml_gpio) + sizeof(aml_i2cd) + sizeof(aml_ecsl) +
		    sizeof(aml_tpad)];
static uint32_t tpad_at;

static uint32_t build_blob(void)
{
	uint32_t n = 0;

	anx_memcpy(blob + n, aml_gpio, sizeof(aml_gpio));
	n += sizeof(aml_gpio);
	anx_memcpy(blob + n, aml_i2cd, sizeof(aml_i2cd));
	n += sizeof(aml_i2cd);
	anx_memcpy(blob + n, aml_ecsl, sizeof(aml_ecsl));
	n += sizeof(aml_ecsl);
	tpad_at = n;
	anx_memcpy(blob + n, aml_tpad, sizeof(aml_tpad));
	n += sizeof(aml_tpad);
	return n;
}

static bool name_is(const struct anx_aml_device *d, const char *name)
{
	return anx_strncmp(d->name, name, 4) == 0;
}

static int hid_devices_in_order(uint32_t len)
{
	struct anx_aml_device d;
	uint32_t pos = 0, found = 0;

	while (anx_aml_next_device(blob, len, &pos, &d)) {
		if (!anx_aml_device_has_id(blob, &d, "PNP0C50"))
			continue;
		if (found == 0)
			CHECK(name_is(&d, "ECSL"), "first HID-over-I2C device is ECSL");
		if (found == 1)
			CHECK(name_is(&d, "TPAD"), "second is TPAD");
		found++;
	}
	CHECK(found == 2, "exactly two PNP0C50 devices");
	return 0;
}

static int touchpad_resources(uint32_t len)
{
	struct anx_aml_device d;
	struct anx_aml_i2c i2c;
	struct anx_aml_gpio_int gpio;
	uint16_t reg;

	CHECK(anx_aml_find_device(blob, len, "TPAD", "PIXA3854", &d),
	      "TPAD found by name and _HID");
	CHECK(d.start == tpad_at && d.end == tpad_at + sizeof(aml_tpad),
	      "TPAD package bounds come from its PkgLength");

	CHECK(anx_aml_i2c(blob, &d, &i2c), "I2cSerialBus found");
	CHECK(i2c.addr == 0x2C, "touchpad address 0x2C");
	CHECK(i2c.speed_hz == 400000, "400 kHz");
	CHECK(anx_strncmp(i2c.bus, "I2CD", 5) == 0, "on controller I2CD");

	CHECK(anx_aml_gpio_int(blob, &d, &gpio), "GpioInt found");
	CHECK(gpio.pin == 8, "interrupt on GPIO pin 8");
	CHECK(gpio.level && gpio.active_low, "level-triggered, active low");
	CHECK(anx_strncmp(gpio.ctrl, "GPIO", 5) == 0, "on controller GPIO");

	CHECK(anx_aml_hid_i2c_desc_reg(blob, &d, &reg), "_DSM constant found");
	CHECK(reg == 0x20, "HID descriptor register 0x20");
	return 0;
}

static int ec_resources(uint32_t len)
{
	struct anx_aml_device d;
	struct anx_aml_i2c i2c;
	struct anx_aml_gpio_int gpio;
	uint16_t reg;

	CHECK(anx_aml_find_device(blob, len, "ECSL", "FRMW0003", &d), "ECSL found");
	CHECK(anx_aml_i2c(blob, &d, &i2c) && i2c.addr == 0x51 &&
	      anx_strncmp(i2c.bus, "I2CB", 5) == 0, "ECSL at 0x51 on I2CB");
	CHECK(anx_aml_gpio_int(blob, &d, &gpio) && gpio.pin == 0x54,
	      "ECSL interrupt on pin 0x54");
	CHECK(anx_aml_hid_i2c_desc_reg(blob, &d, &reg) && reg == 0x55,
	      "ECSL HID descriptor register 0x55");
	return 0;
}

static int controller_addresses(uint32_t len)
{
	struct anx_aml_device d;
	uint32_t base, size;

	CHECK(anx_aml_find_device(blob, len, "I2CD", "AMDI0010", &d),
	      "I2CD found by name and _HID");
	CHECK(anx_aml_mem32(blob, &d, &base, &size), "I2CD Memory32Fixed");
	CHECK(base == 0xFEDC5000 && size == 0x1000, "I2CD at 0xFEDC5000");

	CHECK(anx_aml_find_device(blob, len, "GPIO", "AMDI0030", &d),
	      "GPIO found");
	CHECK(anx_aml_mem32(blob, &d, &base, &size) && base == 0xFED81500 &&
	      size == 0x400, "GPIO bank at 0xFED81500");

	CHECK(!anx_aml_find_device(blob, len, "I2CD", "AMDI0030", &d),
	      "a name with the wrong _HID does not match");
	return 0;
}

static int truncated_table(void)
{
	struct anx_aml_device d;
	uint32_t pos = 0, len = tpad_at + 100;

	while (anx_aml_next_device(blob, len, &pos, &d))
		CHECK(!name_is(&d, "TPAD"),
		      "a package running past the table end is refused");
	return 0;
}

int test_aml_res(void)
{
	uint32_t len = build_blob();

	if (hid_devices_in_order(len))
		return -1;
	if (touchpad_resources(len))
		return -1;
	if (ec_resources(len))
		return -1;
	if (controller_addresses(len))
		return -1;
	if (truncated_table())
		return -1;
	return 0;
}
